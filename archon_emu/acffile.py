from collections import namedtuple
from functools import wraps
from configparser import RawConfigParser
import warnings
from archon_emu.archontypes import *
    
archon_module = namedtuple('module',['position','type','rev','version','id'])
archon_version_string = namedtuple('version',['major','minor','build'])

def firsttime(fun):
    """ decorator for properties which calculates value using wrapped function 
    once, then thereafter serves the calculated value"""
    @wraps(fun)
    def f(self):
        if not hasattr(self,'_'+fun.__name__):
            setattr(self,'_'+fun.__name__,fun(self))
        return getattr(self,'_'+fun.__name__)
    return f

def getnumfromconfig(linename):
    """ decorator which supplies the wrapped function with an expected number
    of values extracted from an archon config. Just here to save a bit of typing later"""
    def wrapper(fun):
        @wraps(fun)
        def f(self):
            n = self.cp['CONFIG'].getint(linename)
            return fun(self,n)
        return f
    return wrapper
    
def valparse(val,empty_is_none=False):
    """ parse valid archon parameter, clock and constant values.
    Values can be floats, ints or strings. Optionally converts empty strings into
    python None values"""
    try:
        v = float(val) if '.' in val else int(val)
        return v
    except ValueError:
        if empty_is_none and  len(val) ==0:
            return None
        return val
    
def defparse(line):
    """ parse an archon definition line"""
    name,val = line.split('=')
    return name, valparse(val)

def versparse(versionstr):
    """parse an archon version string into a namedtuple"""
    return archon_version_string(*[int(_) for _ in versionstr.split('.')])

def listparse(lst):
    """parse an archon value list (comma separated)"""
    return (valparse(_,True) for _ in lst.split(','))
    
def stripline(line):
    """strip quote characters and end of line comments from an archon config line"""
    #strip quotes
    if line.startswith('"') and line.endswith('"'):
        line =  line[1:-1]

    #strip trailing comments
    if '#' in line:
        line = line [:line.index('#')]
    
    #SUPERHACK: too tired to work out how to actually do this
    #SUPERHACK: should be done by ASCII decoding properly
    if line.endswith('\\t'):
        return line.strip('\\t')
    
                 
    #strip tabs: no unicode encoding means this shows up as double backslash
    return line

